const DEVICE_NAMES = {
  he: { garmin: 'Garmin', apple_watch: 'Apple Watch', phone: 'טלפון' },
  en: { garmin: 'Garmin', apple_watch: 'Apple Watch', phone: 'Phone' },
};

let _lang = localStorage.getItem('lang') || 'he';
const _listeners = [];

function getLang() { return _lang; }

function t(key, params) {
  let str = (I18N[_lang] && I18N[_lang][key]) || (I18N.he[key]) || key;
  if (params) Object.keys(params).forEach((k) => { str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), params[k]); });
  return str;
}

function deviceName(id) { return (DEVICE_NAMES[_lang] || DEVICE_NAMES.he)[id] || id; }

function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph'))); });
}

function setLang(lang) {
  _lang = lang === 'en' ? 'en' : 'he';
  localStorage.setItem('lang', _lang);
  document.documentElement.lang = _lang;
  document.documentElement.dir = _lang === 'he' ? 'rtl' : 'ltr';
  applyI18n(document);
  const toggle = document.getElementById('langToggle');
  if (toggle) toggle.textContent = t('lang.toggle');
  _listeners.forEach((fn) => { try { fn(_lang); } catch (e) { /* noop */ } });
}

// onChange: פונקציה שתופעל בעת החלפת שפה (לרינדור מחדש של תוכן דינמי)
function initI18n(onChange) {
  if (onChange) _listeners.push(onChange);
  document.documentElement.lang = _lang;
  document.documentElement.dir = _lang === 'he' ? 'rtl' : 'ltr';
  applyI18n(document);
  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.textContent = t('lang.toggle');
    toggle.addEventListener('click', () => setLang(_lang === 'he' ? 'en' : 'he'));
  }
}

window.i18n = { t, getLang, setLang, applyI18n, initI18n, deviceName };
